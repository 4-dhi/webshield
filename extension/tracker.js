function wsExtractHostname(urlStr) {
  try {
    return new URL(urlStr).hostname.toLowerCase();
  } catch {
    return "";
  }
}

function wsIsThirdParty(requestUrl, pageUrl) {
  if (!pageUrl) return true;
  const reqHost = wsExtractHostname(requestUrl);
  const pageHost = wsExtractHostname(pageUrl);
  if (!reqHost || !pageHost) return true;
  if (reqHost === pageHost) return false;
  if (reqHost.endsWith("." + pageHost) || pageHost.endsWith("." + reqHost)) return false;
  return true;
}

function wsMatchesPatterns(urlStr, patterns) {
  const lower = (urlStr || "").toLowerCase();
  return patterns.some((p) => lower.includes(p));
}

const WS_YOUTUBE_PATTERNS = [
  "googlevideo.com/videoplayback", "youtube.com/api/stats/ads",
  "youtube.com/get_midroll_info", "youtube.com/ptracking",
];

function wsClassifyRequest(urlStr, pageUrl, youtubeAdBlockEnabled = true) {
  const lower = (urlStr || "").toLowerCase();
  const thirdParty = wsIsThirdParty(lower, pageUrl);

  if (wsMatchesPatterns(lower, WS_MINER_PATTERNS)) {
    return { category: "miner", isAd: true, isTracker: false, isMalware: true, thirdParty };
  }
  if (wsMatchesPatterns(lower, WS_FINGERPRINT_PATTERNS)) {
    return { category: "fingerprint", isAd: false, isTracker: true, isMalware: false, thirdParty };
  }
  if (wsMatchesPatterns(lower, WS_PIXEL_PATTERNS)) {
    return { category: "pixel", isAd: false, isTracker: true, isMalware: false, thirdParty };
  }
  if (wsMatchesPatterns(lower, WS_MALWARE_PATTERNS)) {
    return { category: "malware", isAd: false, isTracker: false, isMalware: true, thirdParty };
  }
  
  // Check YouTube patterns only if YouTube ad blocking is enabled
  if (youtubeAdBlockEnabled && wsMatchesPatterns(lower, WS_YOUTUBE_PATTERNS)) {
    return { category: "ad", isAd: true, isTracker: false, isMalware: false, thirdParty };
  }
  
  // Check other ad patterns (excluding YouTube-specific ones)
  if (wsMatchesPatterns(lower, WS_AD_PATTERNS.filter(p => !WS_YOUTUBE_PATTERNS.includes(p)))) {
    return { category: "ad", isAd: true, isTracker: false, isMalware: false, thirdParty };
  }
  
  if (wsMatchesPatterns(lower, WS_TRACKER_PATTERNS)) {
    return { category: "tracker", isAd: false, isTracker: true, isMalware: false, thirdParty };
  }
  return { category: "unknown", isAd: false, isTracker: false, isMalware: false, thirdParty };
}

// Legacy alias used by background.js
function classifyUrl(urlStr) {
  const r = wsClassifyRequest(urlStr);
  return { isAd: r.isAd, isTracker: r.isTracker };
}
